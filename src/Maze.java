    private int currentLevel = 1;
    private String[] layout = levels[0];

    public void setLevel(int level) {
        if (level < 1 || level > levels.length) {
            throw new IllegalArgumentException("Unknown level: " + level);
        }
        currentLevel = level;
        layout = levels[level - 1];
    }

    public int getLevel() { return currentLevel; }
    public int getRows() { return layout.length; }
    public int getCols() { return layout[0].length(); }

    public boolean isInside(int row, int col) {
        return row >= 0 && row < getRows() && col >= 0 && col < getCols();
    }

    public boolean isWall(int row, int col) {
        return !isInside(row, col) || layout[row].charAt(col) == '#';
    }

    public boolean isExit(int row, int col) {
        return isInside(row, col) && layout[row].charAt(col) == 'E';
    }

    public boolean canMoveTo(int row, int col) {
        return isInside(row, col) && !isWall(row, col);
    }
